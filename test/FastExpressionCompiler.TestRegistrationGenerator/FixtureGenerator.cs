using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace FastExpressionCompiler.TestRegistrationGenerator;

[Generator]
public sealed class FixtureGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor InvalidFixture = new DiagnosticDescriptor(
        "FECTEST001", "Invalid registered fixture", "Registered fixture '{0}' must be a public, top-level, non-generic, concrete type with a public parameterless constructor and one supported Run entry point (or an explicit registration group)",
        "TestRegistration", DiagnosticSeverity.Error, true);

    public void Initialize(IncrementalGeneratorInitializationContext context) =>
        context.RegisterSourceOutput(context.CompilationProvider, Emit);

    private static void Emit(SourceProductionContext output, Compilation compilation)
    {
        var fixtures = new List<Fixture>();
        var validateSource = IsFixtureAssembly(compilation.AssemblyName);
        IEnumerable<IAssemblySymbol> assemblies = validateSource
            ? new[] { compilation.Assembly } : compilation.SourceModule.ReferencedAssemblySymbols;
        foreach (var assembly in assemblies)
        {
            var name = assembly.Identity.Name;
            if (!IsFixtureAssembly(name)) continue;
            foreach (var type in GetTypes(assembly.GlobalNamespace))
            {
                output.CancellationToken.ThrowIfCancellationRequested();
                var attribute = type.GetAttributes().FirstOrDefault(a =>
                    a.AttributeClass?.ToDisplayString() == "FastExpressionCompiler.RunTestAttribute" ||
                    a.AttributeClass?.ToDisplayString() == "FastExpressionCompiler.LightExpression.RunTestAttribute");
                if (attribute == null) continue;
                var light = name.Contains(".LightExpression.");
                var testRun = light ? "FastExpressionCompiler.LightExpression.TestRun" : "FastExpressionCompiler.TestRun";
                var testX = type.AllInterfaces.Any(i => i.ToDisplayString() == testRun.Replace(".TestRun", ".ITestX"));
                var legacy = type.GetMembers("Run").OfType<IMethodSymbol>().Any(m =>
                    !m.IsStatic && m.DeclaredAccessibility == Accessibility.Public && m.Parameters.Length == 0 &&
                    m.ReturnType.SpecialType == SpecialType.System_Int32);
                var group = attribute.ConstructorArguments.Length != 0 && attribute.ConstructorArguments[0].Value is int value ? value : 0;
                var contracts = group == 1;
                if (group == 2)
                    testX = false;
                if (group < 0 || group > 2 || type.DeclaredAccessibility != Accessibility.Public || type.ContainingType != null || type.IsAbstract ||
                    type.Arity != 0 || (!type.IsValueType && !type.InstanceConstructors.Any(c => c.DeclaredAccessibility == Accessibility.Public && c.Parameters.Length == 0)) ||
                    (!testX && !legacy) || (testX && legacy) || (contracts && !testX))
                {
                    output.ReportDiagnostic(Diagnostic.Create(InvalidFixture, type.Locations.FirstOrDefault(l => l.IsInSource) ?? Location.None, type.ToDisplayString()));
                    continue;
                }
                fixtures.Add(new Fixture(type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                    testX ? (contracts ? "Contracts" : light ? "Light" : "Standard") : name.EndsWith(".IssueTests", StringComparison.Ordinal) ? "Issues" : "Units", light));
            }
        }

        // Validate before reference assemblies can hide internal/private marked fixtures.
        if (validateSource) return;

        fixtures.Sort((a, b) => StringComparer.Ordinal.Compare(a.Name, b.Name));
        var source = new StringBuilder("// <auto-generated/>\nnamespace FastExpressionCompiler.UnitTests\n{\n    internal static partial class GeneratedTests\n    {\n");
        Method("RunStandard", "global::FastExpressionCompiler.TestRun tests", "Standard", false);
        Method("RunLight", "global::FastExpressionCompiler.LightExpression.TestRun tests", "Light", false);
        Method("RunContracts", "global::FastExpressionCompiler.TestRun standard, global::FastExpressionCompiler.LightExpression.TestRun light", "Contracts", false);
        Method("RunUnitLegacy", "global::System.Action<global::System.Func<int>, string> run", "Units", true);
        Method("RunIssueLegacy", "global::System.Action<global::System.Func<int>, string> run", "Issues", true);
        source.AppendLine("        internal static string[] GetFixtures() => new string[]");
        source.AppendLine("        {");
        foreach (var fixture in fixtures)
            source.Append("            \"").Append(fixture.Group).Append('|').Append(fixture.Name.Substring("global::".Length)).AppendLine("\",");
        source.AppendLine("        };\n    }\n}");
        output.AddSource("GeneratedTests.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));

        void Method(string method, string parameters, string group, bool legacy)
        {
            source.Append("        internal static partial void ").Append(method).Append('(').Append(parameters).AppendLine(")\n        {");
            foreach (var fixture in fixtures.Where(f => f.Group == group))
                if (legacy)
                    source.Append("            run(new ").Append(fixture.Name).Append("().Run, \"").Append(fixture.Name.Substring("global::".Length)).AppendLine("\");");
                else
                    source.Append("            ").Append(group == "Contracts" ? fixture.Light ? "light" : "standard" : "tests")
                        .Append(".Run(new ").Append(fixture.Name).AppendLine("());");
            source.AppendLine("        }");
        }
    }

    private static bool IsFixtureAssembly(string name) =>
        name == "FastExpressionCompiler.UnitTests" || name == "FastExpressionCompiler.IssueTests" ||
        name == "FastExpressionCompiler.LightExpression.UnitTests" || name == "FastExpressionCompiler.LightExpression.IssueTests";

    private static IEnumerable<INamedTypeSymbol> GetTypes(INamespaceSymbol ns)
    {
        foreach (var type in ns.GetTypeMembers())
        {
            yield return type;
            foreach (var nested in GetNestedTypes(type)) yield return nested;
        }
        foreach (var child in ns.GetNamespaceMembers())
            foreach (var type in GetTypes(child)) yield return type;
    }

    private static IEnumerable<INamedTypeSymbol> GetNestedTypes(INamedTypeSymbol owner)
    {
        foreach (var type in owner.GetTypeMembers())
        {
            yield return type;
            foreach (var nested in GetNestedTypes(type)) yield return nested;
        }
    }

    private sealed class Fixture
    {
        internal readonly string Name, Group;
        internal readonly bool Light;
        internal Fixture(string name, string group, bool light) { Name = name; Group = group; Light = light; }
    }
}
